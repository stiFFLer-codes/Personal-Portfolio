// The service worker, generated at build so it knows every page.
//
// "The software I find most worth building is the kind that keeps working
// when the bars hit zero." So this site does: after one visit, every page of
// text is readable with no connection.
//
//   pages   network first. A reader who is online always gets the current
//           page; the saved copy is used only when the network fails.
//   assets  cache first. Files under /_astro/ carry a content hash in their
//           name, so a cached one is never stale.
//
// The cache is named for the build. A new build installs a new worker,
// which takes over at once and deletes the old cache.
//
// To switch this off: delete this file and the registration in Base.astro,
// and ship public/sw.js containing only
//   self.addEventListener('install', () => self.skipWaiting());
//   self.addEventListener('activate', (e) => e.waitUntil(
//     caches.keys().then((k) => Promise.all(k.map((n) => caches.delete(n))))
//       .then(() => self.registration.unregister())));
import type { APIRoute } from 'astro';
import { getCollection } from 'astro:content';
// The Latin files of the three faces, by the same hashed URLs the pages use.
// On a first visit they load before the worker is in control, so they are
// saved here by name (the browser's own cache already holds them).
import fraunces from '@fontsource-variable/fraunces/files/fraunces-latin-soft-normal.woff2?url';
import newsreader from '@fontsource-variable/newsreader/files/newsreader-latin-wght-normal.woff2?url';
import newsreaderItalic from '@fontsource-variable/newsreader/files/newsreader-latin-wght-italic.woff2?url';
import mono from '@fontsource-variable/jetbrains-mono/files/jetbrains-mono-latin-wght-normal.woff2?url';

export const GET: APIRoute = async () => {
  const [research, projects, writing] = await Promise.all([
    getCollection('research'),
    getCollection('projects'),
    getCollection('writing'),
  ]);
  const pages = [
    '/',
    '/unresolved/',
    '/research/',
    '/projects/',
    '/writing/',
    '/travel/',
    ...research.map((e) => `/research/${e.id}/`),
    ...projects.map((e) => `/projects/${e.id}/`),
    ...writing.map((e) => `/writing/${e.id}/`),
    fraunces,
    newsreader,
    newsreaderItalic,
    mono,
    '/favicon.svg',
  ];
  const version = new Date().toISOString().replace(/[-:.TZ]/g, '').slice(0, 14);

  const body = `// Generated by src/pages/sw.js.ts. Do not edit.
const CACHE = 'site-${version}';
const PAGES = ${JSON.stringify(pages)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      // One page failing to save must not stop the rest.
      .then((cache) => Promise.allSettled(PAGES.map((p) => cache.add(p))))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((names) => Promise.all(names.filter((n) => n !== CACHE).map((n) => caches.delete(n))))
      .then(() => self.clients.claim())
  );
});

const save = (request, response) => {
  if (response && response.ok && response.type === 'basic') {
    const copy = response.clone();
    caches.open(CACHE).then((cache) => cache.put(request, copy));
  }
  return response;
};

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => save(request, response))
        .catch(() =>
          caches.match(request, { ignoreSearch: true })
            .then((hit) => hit || caches.match(url.pathname.endsWith('/') ? url.pathname : url.pathname + '/'))
            .then((hit) => hit || caches.match('/'))
        )
    );
    return;
  }

  if (url.pathname.startsWith('/_astro/') || url.pathname === '/favicon.svg') {
    event.respondWith(
      // ignoreVary: a font is asked for with an Origin header and was saved
      // without one. The name carries a content hash, so any copy is the copy.
      caches.match(request, { ignoreVary: true }).then((hit) => hit || fetch(request).then((response) => save(request, response)))
    );
  }
});
`;
  return new Response(body, {
    headers: { 'Content-Type': 'text/javascript; charset=utf-8' },
  });
};
